// scripts/ensure-compass-plugin.js
//
// Generates CompassSensorPlugin.java - a native replacement for the
// current JS-only deviceorientation-based compass in compassHeading.js.
//
// Uses Android's TYPE_ROTATION_VECTOR sensor (accelerometer + gyroscope +
// magnetometer, fused and drift-corrected at the OS level - NOT a custom
// filter reimplementing that fusion, since Android's own is already doing
// the hard part). On top of that:
//   - True-north correction via GeomagneticField (World Magnetic Model,
//     computed locally from lat/lon/altitude - no network call, ever).
//     Needs a location fed in from JS via updateLocation(), since this
//     plugin doesn't run its own location listener (the app already has
//     one in gps.js - no reason to duplicate it).
//   - Light smoothing (circular exponential moving average) on the final
//     heading, to knock down residual jitter - not to fix drift, since
//     the rotation vector sensor already handles that part.
//   - The sensor's own reported accuracy (SensorManager's low/medium/high/
//     unreliable), passed through so the UI can prompt recalibration only
//     when the sensor itself says it's unsure, instead of guessing.
//
// Same idempotent pattern as ensure-storage-plugin.js: safe to run after
// every `npx cap sync android`, safe to run when this plugin already
// exists (it's fully generated content, nothing hand-edited to lose).
//
// Usage: node scripts/ensure-compass-plugin.js
// (or: npm run fix-manifest, which runs this too)

const fs = require('fs');
const path = require('path');
const { ensurePluginRegistered, findMainActivity } = require('./lib/patchMainActivity');

const projectRoot = path.join(__dirname, '..');
const found = findMainActivity(projectRoot);
if (!found) {
  console.error(
    `Couldn't find MainActivity.java under android/app/src/main/java/ - ` +
    `run "npx cap add android" first if the android/ folder doesn't have one yet.`
  );
  process.exit(1);
}
const { dir: javaDir, packageName, file: mainActivityFile } = found;
const pluginFile = path.join(javaDir, 'CompassSensorPlugin.java');

const pluginSource = `package ${packageName};

import android.content.Context;
import android.hardware.GeomagneticField;
import android.hardware.Sensor;
import android.hardware.SensorEvent;
import android.hardware.SensorEventListener;
import android.hardware.SensorManager;

import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;

// Generated by scripts/ensure-compass-plugin.js - safe to regenerate,
// don't hand-edit (changes will be overwritten on the next sync).
//
// Streams a "headingUpdate" event ({heading, accuracy}) built from the
// device's TYPE_ROTATION_VECTOR sensor - Android's own fused, drift-
// corrected accel+gyro+magnetometer orientation - true-north-corrected
// via GeomagneticField using whatever location was last passed in through
// updateLocation(), and lightly smoothed to reduce residual jitter.
@CapacitorPlugin(name = "CompassSensor")
public class CompassSensorPlugin extends Plugin implements SensorEventListener {

    private static final double SMOOTHING_ALPHA = 0.25; // 0-1, higher = more responsive, lower = smoother

    private SensorManager sensorManager;
    private Sensor rotationVectorSensor;
    private boolean listening = false;

    private Double lastLat = null;
    private Double lastLng = null;
    private Double lastAlt = null;

    private Double smoothedHeading = null;
    private int lastAccuracy = SensorManager.SENSOR_STATUS_UNRELIABLE;

    @Override
    public void load() {
        sensorManager = (SensorManager) getContext().getSystemService(Context.SENSOR_SERVICE);
        rotationVectorSensor = sensorManager.getDefaultSensor(Sensor.TYPE_ROTATION_VECTOR);
    }

    @PluginMethod
    public void isAvailable(PluginCall call) {
        JSObject result = new JSObject();
        result.put("available", rotationVectorSensor != null);
        call.resolve(result);
    }

    @PluginMethod
    public void start(PluginCall call) {
        if (rotationVectorSensor != null && !listening) {
            sensorManager.registerListener(this, rotationVectorSensor, SensorManager.SENSOR_DELAY_GAME);
            listening = true;
        }
        call.resolve();
    }

    @PluginMethod
    public void stop(PluginCall call) {
        if (listening) {
            sensorManager.unregisterListener(this);
            listening = false;
            smoothedHeading = null; // don't let a stale value carry into the next session
        }
        call.resolve();
    }

    @PluginMethod
    public void updateLocation(PluginCall call) {
        lastLat = call.getDouble("latitude");
        lastLng = call.getDouble("longitude");
        lastAlt = call.getDouble("altitude", 0.0);
        call.resolve();
    }

    @Override
    protected void handleOnPause() {
        // Stop listening while backgrounded: the rotation vector sensor
        // otherwise keeps firing at SENSOR_DELAY_GAME the whole time the
        // phone is in a pocket, which burns battery for readings nothing
        // is displaying. \`listening\` deliberately stays true so resume
        // knows to re-register.
        if (listening) sensorManager.unregisterListener(this);
    }

    @Override
    protected void handleOnResume() {
        if (listening && rotationVectorSensor != null) {
            smoothedHeading = null; // don't blend the first new reading against a stale pre-pause value
            sensorManager.registerListener(this, rotationVectorSensor, SensorManager.SENSOR_DELAY_GAME);
        }
    }

    @Override
    public void onSensorChanged(SensorEvent event) {
        if (event.sensor.getType() != Sensor.TYPE_ROTATION_VECTOR) return;

        float[] rotationMatrix = new float[9];
        SensorManager.getRotationMatrixFromVector(rotationMatrix, event.values);
        float[] orientation = new float[3];
        SensorManager.getOrientation(rotationMatrix, orientation);
        double magneticHeading = Math.toDegrees(orientation[0]);
        magneticHeading = ((magneticHeading % 360) + 360) % 360;

        double trueHeading = magneticHeading;
        if (lastLat != null && lastLng != null) {
            GeomagneticField field = new GeomagneticField(
                lastLat.floatValue(),
                lastLng.floatValue(),
                lastAlt != null ? lastAlt.floatValue() : 0f,
                System.currentTimeMillis()
            );
            trueHeading = ((magneticHeading + field.getDeclination()) % 360 + 360) % 360;
        }

        smoothedHeading = smooth(trueHeading);

        JSObject data = new JSObject();
        data.put("heading", smoothedHeading);
        data.put("accuracy", accuracyLabel(lastAccuracy));
        notifyListeners("headingUpdate", data);
    }

    @Override
    public void onAccuracyChanged(Sensor sensor, int accuracy) {
        lastAccuracy = accuracy;
    }

    // Circular exponential moving average - a plain EMA breaks across the
    // 0/360 seam (naively averaging 359 and 1 gives 180, not 0), so this
    // moves toward the new reading by the shortest angular path instead.
    private double smooth(double newHeading) {
        if (smoothedHeading == null) return newHeading;
        double delta = newHeading - smoothedHeading;
        delta = ((delta + 180) % 360 + 360) % 360 - 180;
        return ((smoothedHeading + delta * SMOOTHING_ALPHA) % 360 + 360) % 360;
    }

    private String accuracyLabel(int accuracy) {
        switch (accuracy) {
            case SensorManager.SENSOR_STATUS_ACCURACY_HIGH: return "high";
            case SensorManager.SENSOR_STATUS_ACCURACY_MEDIUM: return "medium";
            case SensorManager.SENSOR_STATUS_ACCURACY_LOW: return "low";
            default: return "unreliable";
        }
    }
}
`;

fs.writeFileSync(pluginFile, pluginSource);
console.log(`Wrote ${pluginFile}`);

const mainActivity = fs.readFileSync(mainActivityFile, 'utf8');
const result = ensurePluginRegistered(mainActivity, 'CompassSensorPlugin');
console.log(result.message);
if (result.changed) {
  fs.writeFileSync(mainActivityFile, result.content);
}
if (result.error) {
  process.exit(1);
}
