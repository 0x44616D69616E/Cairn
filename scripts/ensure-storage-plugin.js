// scripts/ensure-storage-plugin.js
//
// MANAGE_EXTERNAL_STORAGE ("All files access") isn't a normal runtime
// permission - the only way to grant it is sending the user to a specific
// system Settings screen via the ACTION_MANAGE_APP_ALL_FILES_ACCESS_PERMISSION
// intent, and @capacitor/filesystem has no way to launch that itself. This
// needs a small custom native plugin: two methods, "is it granted" and
// "send the user to go grant it."
//
// Like ensure-manifest-permissions.js, this is safe to run after every
// single `npx cap sync android` - it writes the plugin file fresh every
// time (it's fully generated content, nothing hand-edited to preserve),
// and only touches MainActivity.java if the plugin isn't registered yet.
//
// Usage: node scripts/ensure-storage-plugin.js
// (or: npm run fix-manifest, which runs this too)

const fs = require('fs');
const path = require('path');
const { ensurePluginRegistered, findMainActivity } = require('./lib/patchMainActivity');

const projectRoot = path.join(__dirname, '..');
const found = findMainActivity(projectRoot);
if (!found) {
  console.error(
    `Couldn't find MainActivity.java under android/app/src/main/java/ - ` +
    `run "npx cap add android" first if the android/ folder doesn't have one yet.`
  );
  process.exit(1);
}
const { dir: javaDir, packageName, file: mainActivityFile } = found;
const pluginFile = path.join(javaDir, 'AllFilesAccessPlugin.java');

const pluginSource = `package ${packageName};

import android.content.Intent;
import android.net.Uri;
import android.os.Build;
import android.os.Environment;
import android.provider.Settings;

import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;

// Generated by scripts/ensure-storage-plugin.js - safe to regenerate,
// don't hand-edit (changes will be overwritten on the next sync).
//
// MANAGE_EXTERNAL_STORAGE ("All files access") can only be granted by
// sending the user to a specific system Settings screen - there's no
// normal runtime permission dialog for it. Once granted, though,
// @capacitor/filesystem's Directory.EXTERNAL_STORAGE starts working with
// real file paths again (it uses plain java.io.File under the hood,
// which is exactly what this permission restores access to).
@CapacitorPlugin(name = "AllFilesAccess")
public class AllFilesAccessPlugin extends Plugin {

    @PluginMethod
    public void isGranted(PluginCall call) {
        JSObject result = new JSObject();
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            result.put("granted", Environment.isExternalStorageManager());
        } else {
            result.put("granted", true); // permission model doesn't exist before Android 11
        }
        call.resolve(result);
    }

    @PluginMethod
    public void requestAccess(PluginCall call) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
            try {
                Intent intent = new Intent(Settings.ACTION_MANAGE_APP_ALL_FILES_ACCESS_PERMISSION);
                intent.setData(Uri.parse("package:" + getContext().getPackageName()));
                getActivity().startActivity(intent);
            } catch (Exception e) {
                getActivity().startActivity(new Intent(Settings.ACTION_MANAGE_ALL_FILES_ACCESS_PERMISSION));
            }
        }
        call.resolve();
    }
}
`;

fs.writeFileSync(pluginFile, pluginSource);
console.log(`Wrote ${pluginFile}`);

const mainActivity = fs.readFileSync(mainActivityFile, 'utf8');
const result = ensurePluginRegistered(mainActivity, 'AllFilesAccessPlugin');
console.log(result.message);
if (result.changed) {
  fs.writeFileSync(mainActivityFile, result.content);
}
if (result.error) {
  process.exit(1);
}
